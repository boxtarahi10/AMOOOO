export const LEVELS_PER_CITY = 30;

export function getCityForLevel(level: number) {
  const ci = Math.min(Math.floor((level - 1) / LEVELS_PER_CITY), IRAN_ROUTE.length - 1);
  return { cityIndex: ci, cityName: IRAN_ROUTE[ci], levelInCity: ((level - 1) % LEVELS_PER_CITY) + 1, icon: CITY_ICONS[ci] || '📍' };
}
