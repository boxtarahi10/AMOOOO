const chapters = ['festivals', 'cities', 'mystery', 'literature', 'shahnameh'];

export function getChapterWords(chapter: number) {
  const catKey = chapters[Math.min(chapter - 1, chapters.length - 1)];
  return {
    dominant: wordBank[catKey] || [],
    connector: wordBank.connectors || [],
    other: Object.entries(wordBank)
      .filter(([key]) => key !== catKey && key !== 'connectors')
      .flatMap(([, words]) => words),
  };
}

export function getChapterName(chapter: number): string {
  const names = ['باب اول: آیین و جشن', 'باب دوم: سرزمین ایران', 'باب سوم: رمز و راز', 'باب چهارم: سخن و ادب', 'باب پنجم: حماسه و اسطوره'];
  return names[Math.min(chapter - 1, names.length - 1)];
}
